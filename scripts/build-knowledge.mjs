#!/usr/bin/env node
// Generates site/knowledge.json from every *.html page in the repo root: slug, title, description, h1, h2s and
// the first ~1200 characters of body text (shared chrome stripped). The chat's "question" state answers from it.
//   npm run build:knowledge
// No dependencies. Re-run after page content changes; commit the result so Vercel ships it with the functions.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'site', 'knowledge.json')
const MAX_TEXT = 1200
const SKIP = new Set(['404.html', 'sitemap.html'])

const decode = (s) => s
  .replace(/&nbsp;/g, ' ').replace(/&rsquo;/g, '’').replace(/&lsquo;/g, '‘').replace(/&ldquo;/g, '“').replace(/&rdquo;/g, '”')
  .replace(/&mdash;/g, '—').replace(/&ndash;/g, '–').replace(/&hellip;/g, '…').replace(/&middot;/g, '·').replace(/&amp;/g, '&')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
const squash = (s) => decode(s).replace(/\s+/g, ' ').trim()
const strip = (html) => squash(html.replace(/<[^>]+>/g, ' '))

function stripChrome(html) {
  let h = html
  h = h.replace(/<!-- build:(\w+) -->[\s\S]*?<!-- \/build:\1 -->/g, ' ')
  h = h.replace(/<(script|style|noscript|template|svg)\b[\s\S]*?<\/\1>/gi, ' ')
  h = h.replace(/<(header|footer|nav|form)\b[\s\S]*?<\/\1>/gi, ' ')
  h = h.replace(/<div class="chat-widget"[\s\S]*?<\/div>\s*<\/div>\s*<\/div>/gi, ' ')
  h = h.replace(/<section class="contact"[\s\S]*?<\/section>/gi, ' ')
  h = h.replace(/<(div|aside)[^>]*(consent|cookie)[^>]*>[\s\S]*?<\/\1>/gi, ' ')
  return h
}

function extract(file) {
  const html = fs.readFileSync(path.join(ROOT, file), 'utf8')
  const slug = file.replace(/\.html$/, '')
  const title = squash(html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || slug)
  const description = squash(html.match(/<meta\s+name=["']description["']\s+content=["']([^"']*)["']/i)?.[1] || '')
  const body = stripChrome(html.match(/<body[^>]*>([\s\S]*)<\/body>/i)?.[1] || html)
  const main = body.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i)?.[1] || body
  const h1 = strip(main.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || body.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || '')
  const h2s = [...main.matchAll(/<h2\b[^>]*>([\s\S]*?)<\/h2>/gi)].map((m) => strip(m[1])).filter(Boolean).filter((v, i, a) => a.indexOf(v) === i).slice(0, 12)
  const text = strip(main.replace(/<h1\b[\s\S]*?<\/h1>/i, ' ')).slice(0, MAX_TEXT)
  return { slug, title, description, h1, h2s, text }
}

const files = fs.readdirSync(ROOT).filter((f) => f.endsWith('.html') && !SKIP.has(f)).sort()
const pages = files.map(extract)
const out = { _readme: 'Generated by scripts/build-knowledge.mjs — do not edit by hand. Used by lib/chat/knowledge.ts.', generatedAt: new Date().toISOString(), pages }
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n')
console.log(`knowledge: ${pages.length} pages → ${path.relative(ROOT, OUT)}`)
